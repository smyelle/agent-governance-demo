"""6-Stage A-La-Carte Closed-Loop Agent Evaluation & Prompt Optimization Engine.

Executes the 6-stage modular quality flywheel (<25s interactive execution):
1. Production Telemetry Ingestion: Parses multi-cloud OTLP / Langfuse trace bundles
   (`aws`, `azure`, `gcp` spans from `evals/langfuse_trace_fixtures.json`).
2. Automated Failure Extraction: Clusters session anomalies, low user satisfaction,
   governance-freeze violations, and unhandled HTTP 503 MCP tool failures.
3. Automated LLM Evaluation: Invokes `agentplatform.Client.evals.evaluate()` +
   `gemini-3.8-flash` LLM-as-a-judge rubrics (`0-100 behavior_score`; `v1=58.0` BLOCKED).
4. Automated Prompt & Few-Shot Optimization: Dynamically synthesizes improved `v2`
   system instructions and targeted few-shot exemplars via `gemini-3.8-flash`.
5. Synthetic Adversarial & gVisor Stress-Testing: Executes 8 adversarial, PII,
   freeze, and HTTP 503 simulations (`CymbalEnvironmentSimulator` + gVisor math).
6. Automated Registry Deployment: Emits the Golden Blueprint JSON payload for
   Enterprise Catalog (Agent 365 compatible) and updates GCP Agent Registry + Firestore.
"""

