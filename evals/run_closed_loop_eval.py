class SynthesizedPromptArtifact(BaseModel):
    """Structured output generated by Gemini 3.8 Flash Prompt Optimizer."""

    rewritten_rules_section: str = Field(
        description="Concise governance & fault-resilience rules addressing extracted failure clusters."
    )
    few_shot_exemplars: list[str] = Field(
        description="2 concise input->behavior few-shot exemplars preventing freeze bypass and 503 fabrication."
    )
    optimizer_rationale: str = Field(
        description="Single-sentence summary (no typographic dashes) of why v1 failed and how v2 fixes it."
    )


def get_writable_prompts_dir() -> Path:
    """Returns writable prompts directory (supports non-root Cloud Run containers)."""
    runtime_dir = os.getenv("CYMBAL_RUNTIME_STATE_DIR")
    if runtime_dir or not os.access(PROMPTS_DIR, os.W_OK):
        base = Path(runtime_dir or "/tmp/cymbal_runtime_state") / "prompts"
        base.mkdir(parents=True, exist_ok=True)
        for seed_name in (
            "active_version.json",
            "synthesizer_v1_flawed.txt",
            "synthesizer_v2_optimized.txt",
        ):
            src = PROMPTS_DIR / seed_name
            dst = base / seed_name
            if src.is_file() and not dst.is_file():
                dst.write_text(src.read_text(encoding="utf-8"), encoding="utf-8")
        return base
    return PROMPTS_DIR


